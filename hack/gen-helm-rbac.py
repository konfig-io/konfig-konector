#!/usr/bin/env python3
"""Generate helm/konfig-konector/templates/clusterrole.yaml from the CRDs in
config/crd/bases so the chart's RBAC never drifts from the operator's kinds.
Run by `make manifests`."""
import glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
plurals = sorted(os.path.basename(p)[len("aws.konfig.io_"):-len(".yaml")]
                 for p in glob.glob(os.path.join(ROOT, "config/crd/bases/aws.konfig.io_*.yaml")))

def block(suffix):
    return "".join(f"      - {p}{suffix}\n" for p in plurals)

out = f"""{{{{- if .Values.rbac.create }}}}
# Generated by hack/gen-helm-rbac.py from config/crd/bases. DO NOT EDIT.
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: konfig-konector-manager
  labels:
    app.kubernetes.io/name: konfig-konector
rules:
  - apiGroups: ["aws.konfig.io"]
    resources:
{block("")}    verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
  - apiGroups: ["aws.konfig.io"]
    resources:
{block("/status")}    verbs: ["get", "update", "patch"]
  - apiGroups: ["aws.konfig.io"]
    resources:
{block("/finalizers")}    verbs: ["update"]
  # Generated Cloud Control typed kinds (config/crd/cloudcontrol bundles) are
  # installed on demand; the operator owns the whole API group.
  - apiGroups: ["aws.konfig.io"]
    resources: ["*"]
    verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
  - apiGroups: [""]
    resources: ["secrets"]
    verbs: ["get", "list", "watch"]
  - apiGroups: [""]
    resources: ["serviceaccounts"]
    verbs: ["get", "list", "watch", "update", "patch"]
  # Namespaces: the aws.konfig.io/provider annotation selects a namespace's
  # default AWSProvider (multi-account).
  - apiGroups: [""]
    resources: ["namespaces"]
    verbs: ["get", "list", "watch"]
  - apiGroups: ["coordination.k8s.io"]
    resources: ["leases"]
    verbs: ["get", "list", "watch", "create", "update", "patch", "delete"]
  - apiGroups: [""]
    resources: ["events"]
    verbs: ["create", "patch"]
{{{{- end }}}}
"""
open(os.path.join(ROOT, "helm/konfig-konector/templates/clusterrole.yaml"), "w").write(out)
print(f"helm clusterrole: {len(plurals)} aws.konfig.io resources")
