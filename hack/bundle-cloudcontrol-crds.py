#!/usr/bin/env python3
"""Move generated Cloud Control kind CRDs out of config/crd/bases (so the
default install and Helm chart stay lean) into per-service bundles at
config/crd/cloudcontrol/<service>.yaml. Run by `make manifests` after
controller-gen. Install a bundle with `kubectl apply -f`; the operator only
starts controllers for kinds whose CRD is installed."""
import glob, json, os, re, shutil
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manifest_path = os.path.join(ROOT, "hack/gen-cloudcontrol/kinds.json")
if not os.path.exists(manifest_path):
    raise SystemExit(0)
kinds = {m["kind"]: m for m in json.load(open(manifest_path))}
out_dir = os.path.join(ROOT, "config/crd/cloudcontrol")
shutil.rmtree(out_dir, ignore_errors=True)
os.makedirs(out_dir)
bundles, moved = {}, 0
for path in sorted(glob.glob(os.path.join(ROOT, "config/crd/bases/aws.konfig.io_*.yaml"))):
    text = open(path).read()
    m = re.search(r"^    kind: (\w+)$", text, re.M)
    if not m or m.group(1) not in kinds:
        continue
    svc = kinds[m.group(1)]["service"]
    bundles.setdefault(svc, []).append(text.rstrip("\n") + "\n")
    os.remove(path)
    moved += 1
for svc, docs in sorted(bundles.items()):
    open(os.path.join(out_dir, svc + ".yaml"), "w").write("---\n".join(docs))
index = ["# Cloud Control typed-kind CRD bundles (generated by make manifests)", "",
         "| Service | Kinds | Install |", "|---|---|---|"]
for svc, docs in sorted(bundles.items()):
    index.append("| %s | %d | `kubectl apply -f config/crd/cloudcontrol/%s.yaml` |" % (svc, len(docs), svc))
open(os.path.join(out_dir, "README.md"), "w").write("\n".join(index) + "\n")
print("cloudcontrol CRD bundles: %d kinds in %d services" % (moved, len(bundles)))
